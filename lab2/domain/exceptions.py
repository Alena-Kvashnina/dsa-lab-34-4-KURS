"""Доменные исключения.

Отдельная иерархия для ошибок предметной области — чтобы код,
вызывающий операцию, мог явно отличить нарушение бизнес-правила
от технического сбоя (обрыв соединения с БД, файл не найден и т.д.).
"""


class DomainError(Exception):
    """Базовый класс для всех доменных ошибок."""


class DomainInvariantViolation(DomainError):
    """Операция нарушает инвариант предметной области.

    Пример: попытка взять книгу, если нет свободных экземпляров.
    """


class InvalidValueObject(DomainError):
    """Объект-значение создаётся с некорректными данными.

    Пример: отрицательная сумма денег, дата возврата раньше даты выдачи.
    """


class NotFoundError(DomainError):
    """Запрошенный агрегат не найден в репозитории."""
